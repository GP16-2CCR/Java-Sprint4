CREATE TABLE TRECHO_RODOVIA (
    ID_TRECHO NUMBER PRIMARY KEY,
    KM NUMBER(10,2) NOT NULL,
    TIPO_TERRENO VARCHAR2(30) NOT NULL,
    TIPO_CRESCIMENTO VARCHAR2(30) NOT NULL,
    ALTURA_VEGETACAO_CM NUMBER(10,2) NOT NULL,
    EQUIPADO_IOT NUMBER(1) NOT NULL,
    POSSUI_INVASORAS NUMBER(1) NOT NULL,
    DIAS_SEM_MANUTENCAO NUMBER NOT NULL,
    NIVEL_PRIORIDADE NUMBER NOT NULL,
    CONSTRAINT CK_TRECHO_TERRENO CHECK (TIPO_TERRENO IN ('UMIDO', 'SECO')),
    CONSTRAINT CK_TRECHO_CRESCIMENTO CHECK (TIPO_CRESCIMENTO IN ('UMIDO', 'SECO')),
    CONSTRAINT CK_TRECHO_IOT CHECK (EQUIPADO_IOT IN (0, 1)),
    CONSTRAINT CK_TRECHO_INVASORAS CHECK (POSSUI_INVASORAS IN (0, 1))
);

CREATE TABLE EQUIPE_MANUTENCAO (
    ID_EQUIPE NUMBER PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    TIPO_EQUIPE VARCHAR2(30) NOT NULL,
    DISPONIVEL NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_EQUIPE_TIPO CHECK (TIPO_EQUIPE IN ('MANUAL', 'MECANIZADA')),
    CONSTRAINT CK_EQUIPE_DISPONIVEL CHECK (DISPONIVEL IN (0, 1))
);

CREATE TABLE INTERVENCAO_OPERACIONAL (
    ID_INTERVENCAO NUMBER PRIMARY KEY,
    TIPO_INTERVENCAO VARCHAR2(30) NOT NULL,
    NOME_SERVICO VARCHAR2(100) NOT NULL,
    CONSTRAINT CK_TIPO_INTERVENCAO CHECK (TIPO_INTERVENCAO IN ('PULVERIZACAO', 'ROCADA_MECANIZADA'))
);

CREATE TABLE RELATORIO_PRIORIDADE (
    ID_RELATORIO NUMBER PRIMARY KEY,
    DATA_GERACAO TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ITEM_RELATORIO (
    ID_ITEM NUMBER PRIMARY KEY,
    ID_RELATORIO NUMBER NOT NULL,
    ID_TRECHO NUMBER NOT NULL,
    ID_INTERVENCAO NUMBER NOT NULL,
    PRIORIDADE NUMBER NOT NULL,
    CONSTRAINT CK_ITEM_PRIORIDADE CHECK (PRIORIDADE BETWEEN 0 AND 100),
    CONSTRAINT FK_ITEM_RELATORIO_RELATORIO FOREIGN KEY (ID_RELATORIO) REFERENCES RELATORIO_PRIORIDADE (ID_RELATORIO) ON DELETE CASCADE,
    CONSTRAINT FK_ITEM_RELATORIO_TRECHO FOREIGN KEY (ID_TRECHO) REFERENCES TRECHO_RODOVIA (ID_TRECHO),
    CONSTRAINT FK_ITEM_RELATORIO_INTERVENCAO FOREIGN KEY (ID_INTERVENCAO) REFERENCES INTERVENCAO_OPERACIONAL (ID_INTERVENCAO)
);

