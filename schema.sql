CREATE SEQUENCE SEQ_TRECHO_RODOVIA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_EQUIPE_MANUTENCAO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
